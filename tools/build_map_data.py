"""Build the offline coastline shared by LCD and web (Natural Earth, public domain).

Only reads ESRI PolyLine coordinates; stdlib only. The downloaded source archive
is cached under build/. Review the SHA-256 in the output when regenerating.
"""
from pathlib import Path
import hashlib
import io
import json
import struct
import urllib.request
import zipfile

root=Path(__file__).resolve().parents[1]
url='https://naciscdn.org/naturalearth/110m/physical/ne_110m_coastline.zip'
archive=root/'build/ne_110m_coastline.zip'
archive.parent.mkdir(parents=True,exist_ok=True)
if not archive.exists():
    with urllib.request.urlopen(url,timeout=45) as response:
        archive.write_bytes(response.read())
data=archive.read_bytes()
with zipfile.ZipFile(io.BytesIO(data)) as z:
    shp=z.read('ne_110m_coastline.shp')
assert struct.unpack_from('>i',shp,0)[0]==9994
paths=[];offset=100
while offset<len(shp):
    size=struct.unpack_from('>i',shp,offset+4)[0]*2
    record=shp[offset+8:offset+8+size];offset+=8+size
    assert struct.unpack_from('<i',record)[0]==3
    parts,points=struct.unpack_from('<ii',record,36)
    starts=list(struct.unpack_from('<'+'i'*parts,record,44))+[points]
    xy=[struct.unpack_from('<dd',record,44+parts*4+i*16) for i in range(points)]
    for first,last in zip(starts,starts[1:]):
        paths.append([[round(lon*100),round(lat*100)] for lon,lat in xy[first:last]])
header='/* Generated by tools/build_map_data.py; Natural Earth 110m coastline, public domain. */\n'
header+='#pragma once\n#include <stdint.h>\nstatic const int16_t sdr_coastline[][2]={\n'
header+='\n'.join(','.join('{%d,%d}'%tuple(p) for p in line)+',{32767,32767},' for line in paths)
header+='\n};\n'
(root/'main/sdr_map_data.h').write_text(header,encoding='utf-8')
(root/'main/map_data.json').write_text(json.dumps({'scale':100,'source':'Natural Earth 110m / public domain','paths':paths},separators=(',',':')),encoding='utf-8')
print('Source',url,'SHA256',hashlib.sha256(data).hexdigest())
print('Coastline paths',len(paths),'vertices',sum(map(len,paths)))
